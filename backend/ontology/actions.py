def __getattr__(name: str):
    """模块级懒转发：ACTION_MAP 指向 registry 实时缓存代理（避免循环导入）"""
    if name == "ACTION_MAP":
        from ontology.registry import ACTION_MAP as _m
        return _m
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


