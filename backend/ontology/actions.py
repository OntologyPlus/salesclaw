# ACTION_MAP：动作名 → 元信息 的实时映射（转发到 registry 权威源）。
# 早期代码在 _pick_actions 引用了 ACTION_MAP，但从未定义，导致
# recommend_actions_for_diagnosis 抛 NameError（影响 /ontology/actions 路径）。
# 这里用属性式代理，确保 reload() 后依然指向最新缓存。
class _ActionMapProxy:
    def __getitem__(self, name: str):
        from ontology.registry import registry
        return registry.action_map[name]

    def get(self, name: str, default=None):
        from ontology.registry import registry
        return registry.action_map.get(name, default)


ACTION_MAP = _ActionMapProxy()


# ──────────────────────────────────────────────
# OAG Layer 5 借鉴点：诊断结论 → 可触发动作最小闭环
# 复用现有 Action 注册表，按诊断 level / domain 推荐 1-3 个动作
# （不新增审批流，仅关联既有 Action 元信息供前端触发）
# ──────────────────────────────────────────────

# 每个诊断域优先关联的候选动作（按优先级，最多取前 3 个存在的）
_DOMAIN_ACTION_CANDIDATES: dict[str, list[str]] = {
    "coverage": ["compute_coverage_gap", "list_coverage_assignments", "create_coverage_assignment"],
    "visit": ["get_coverage_matrix", "create_visit_plan", "list_visit_records"],
    "adoption": ["enroll_course", "list_courses", "update_learning_progress"],
    "training": ["enroll_course", "list_courses", "generate_exam"],
    "decision": ["confirm_diagnosis", "run_simulation", "list_alerts"],
    "compliance": ["list_alerts", "create_approval", "dispatch_alert"],
    "sales": ["list_kpi_values", "compute_kpi", "run_attribution"],
}

# 不同 level 的兜底/强制动作（确保所有 level 都能给出建议）
_LEVEL_FALLBACK: dict[str, list[str]] = {
    "RED": ["confirm_diagnosis", "create_todo", "dispatch_alert"],
    "BLACK": ["confirm_diagnosis", "create_approval", "dispatch_alert"],
    "YELLOW": ["create_todo", "enroll_course", "list_alerts"],
    "GREEN": ["list_kpi_values", "create_todo"],
}


def _pick_actions(candidates: list[str], limit: int = 3) -> list[dict]:
    """从候选名中挑出已注册的 Action 元信息（最多 limit 个）"""
    picked: list[dict] = []
    for name in candidates:
        action = ACTION_MAP.get(name)
        if action and name not in {p["action"] for p in picked}:
            picked.append({
                "action": action["name"],
                "display_name": action["display_name"],
                "risk_level": action["risk_level"],
                "description": action["description"],
            })
        if len(picked) >= limit:
            break
    return picked


def recommend_actions_for_diagnosis(level: str, domain: Optional[str] = None,
                                    syndrome: Optional[str] = None) -> list[dict]:
    """为诊断结论推荐可触发动作（OAG Layer 5 最小闭环）。

    复用 ontology/actions 现有注册表，不新增 Action / 审批流。
    推荐策略：
    - 优先按诊断 domain 取该域相关候选动作；
    - 再按 level 兜底补充（RED/BLACK 强制含 confirm_diagnosis 闭环动作）；
    - 最多返回 3 个已注册动作元信息。

    Returns:
        [{action, display_name, risk_level, description}, ...]
    """
    level = (level or "YELLOW").upper()
    domain = (domain or "").lower()

    candidates: list[str] = []
    if domain in _DOMAIN_ACTION_CANDIDATES:
        candidates.extend(_DOMAIN_ACTION_CANDIDATES[domain])
    # 兜底：确保任何 level 都至少给出建议
    candidates.extend(_LEVEL_FALLBACK.get(level, _LEVEL_FALLBACK["YELLOW"]))

    # syndrome 关键字可进一步精选（保留扩展位，目前仅作候选前缀）
    picked = _pick_actions(candidates, limit=3)
    # 若仍为空（异常），至少返回 confirm_diagnosis 闭环动作
    if not picked:
        picked = _pick_actions(["confirm_diagnosis"], limit=1)
    return picked
